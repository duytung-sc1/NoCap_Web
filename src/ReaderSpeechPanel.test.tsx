// @vitest-environment jsdom
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { ReaderSpeechPanel } from './ReaderSpeechPanel'
import type { ReaderSpeechSource, ReaderSpeechText } from './readerSpeech'
import { MockSynthesis, MockUtterance, speechVoice } from './readerSpeech.testUtils'

let synthesis: MockSynthesis
const source = vi.fn<ReaderSpeechSource>()
const props = { lang: 'en' as const, language: 'vi', source, selection: 'Selected Vietnamese text.', scopeKey: 'section:one', onClose: vi.fn() }
function deferred<T>() { let resolve!: (value: T) => void; const promise = new Promise<T>(done => { resolve = done }); return { resolve, promise } }
beforeEach(() => {
  synthesis = new MockSynthesis()
  vi.stubGlobal('speechSynthesis', synthesis.api()); vi.stubGlobal('SpeechSynthesisUtterance', MockUtterance)
  source.mockReset().mockResolvedValue({ text: 'Current chapter text.', label: 'Chapter one', truncated: false })
  props.onClose.mockClear()
})
afterEach(() => { cleanup(); vi.unstubAllGlobals() })
describe('read aloud panel', () => {
  it('selects a local Vietnamese female voice and gentle delivery, while retaining an explicitly selected voice after discovery', () => {
    const male = speechVoice('vi-VN', true, 'Microsoft An - Vietnamese (Vietnam)')
    const female = speechVoice('vi-VN', true, 'Linh')
    synthesis.voices = [male, female]
    render(<ReaderSpeechPanel {...props} />)
    expect((screen.getByLabelText('Voice') as HTMLSelectElement).selectedOptions[0].textContent).toContain('Linh')
    expect((screen.getByLabelText('Speed') as HTMLSelectElement).value).toBe('0.9')
    expect((screen.getByLabelText('Delivery') as HTMLSelectElement).value).toBe('gentle')
    const maleOption = screen.getByRole('option', { name: /Microsoft An/ }) as HTMLOptionElement
    fireEvent.change(screen.getByLabelText('Voice'), { target: { value: maleOption.value } })
    act(() => { synthesis.voices = [...synthesis.voices]; synthesis.dispatchEvent(new Event('voiceschanged')) })
    expect((screen.getByLabelText('Voice') as HTMLSelectElement).value).toBe(maleOption.value)
    fireEvent.change(screen.getByLabelText('Delivery'), { target: { value: 'natural' } })
    expect((screen.getByLabelText('Speed') as HTMLSelectElement).value).toBe('1')
    fireEvent.click(screen.getByRole('button', { name: 'Vietnamese female · gentle' }))
    expect((screen.getByLabelText('Voice') as HTMLSelectElement).selectedOptions[0].textContent).toContain('Linh')
    expect((screen.getByLabelText('Speed') as HTMLSelectElement).value).toBe('0.9')
    expect((screen.getByLabelText('Delivery') as HTMLSelectElement).value).toBe('gentle')
  })
  it('previews a fixed Vietnamese sample without loading or reading the book or selection', async () => {
    render(<ReaderSpeechPanel {...props} source={null} selection="" />)
    fireEvent.click(screen.getByRole('button', { name: 'Preview voice' }))
    await waitFor(() => expect(synthesis.spoken).toHaveLength(1))
    expect(synthesis.spoken[0].text).toContain('Chào bạn')
    expect(synthesis.spoken[0].rate).toBe(0.9)
    expect(synthesis.spoken[0].pitch).toBe(1)
    expect(source).not.toHaveBeenCalled()
    expect(screen.getByRole('button', { name: 'Read current section' })).toHaveProperty('disabled', true)
  })
  it('reports missing or unidentified female voices honestly and discovers an eligible local female voice later', () => {
    synthesis.voices = [speechVoice('vi-VN', true, 'Microsoft An - Vietnamese (Vietnam)'), speechVoice('vi-VN', false, 'HoaiMyNeural')]
    render(<ReaderSpeechPanel {...props} />)
    expect(screen.getByRole('button', { name: 'Vietnamese female · gentle' })).toHaveProperty('disabled', true)
    expect(screen.getByText(/No Vietnamese female voice could be identified/)).toBeTruthy()
    expect(screen.queryByRole('option', { name: /HoaiMy/ })).toBeNull()
    act(() => { synthesis.voices.push(speechVoice('vi-VN', true, 'Linh')); synthesis.dispatchEvent(new Event('voiceschanged')) })
    expect(screen.getByRole('button', { name: 'Vietnamese female · gentle' })).toHaveProperty('disabled', false)
    expect(screen.queryByText(/No Vietnamese female voice could be identified/)).toBeNull()
    expect((screen.getByLabelText('Voice') as HTMLSelectElement).selectedOptions[0].textContent).toContain('Linh')
  })
  it('reads the selected local voice, pauses/resumes and stops without changing book position', async () => {
    render(<ReaderSpeechPanel {...props} />)
    fireEvent.click(screen.getByRole('button', { name: 'Read current section' }))
    await waitFor(() => expect(synthesis.spoken).toHaveLength(1))
    expect(synthesis.spoken[0].text).toBe('Current chapter text.')
    expect(synthesis.spoken[0].voice?.lang).toBe('vi-VN')
    fireEvent.click(screen.getByRole('button', { name: 'Pause' }))
    expect(synthesis.pause).toHaveBeenCalledOnce()
    fireEvent.click(screen.getByRole('button', { name: 'Resume' }))
    expect(screen.getByRole('button', { name: 'Pause' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Stop' }))
    act(() => synthesis.spoken[0].end())
    expect(synthesis.spoken).toHaveLength(1)
    expect(screen.queryByRole('button', { name: 'Pause' })).toBeNull()
  })
  it('can read just the selection without fetching a chapter', async () => {
    render(<ReaderSpeechPanel {...props} />)
    fireEvent.click(screen.getByRole('button', { name: 'Read selection' }))
    await waitFor(() => expect(synthesis.spoken).toHaveLength(1))
    expect(synthesis.spoken[0].text).toBe(props.selection)
    expect(source).not.toHaveBeenCalled()
  })
  it('uses the latest speed if it changes while a section is being prepared', async () => {
    const pending = deferred<ReaderSpeechText>(); source.mockReturnValueOnce(pending.promise)
    render(<ReaderSpeechPanel {...props} />)
    fireEvent.click(screen.getByRole('button', { name: 'Read current section' }))
    fireEvent.change(screen.getByLabelText('Speed'), { target: { value: '1.5' } })
    act(() => pending.resolve({ text: 'Prepared text.', label: '', truncated: false }))
    await waitFor(() => expect(synthesis.spoken).toHaveLength(1))
    expect(synthesis.spoken[0].rate).toBe(1.5)
  })
  it('does not offer remote voices by default, and responds to late local voice discovery', () => {
    synthesis.voices = [speechVoice('vi-VN', false, 'Cloud voice')]
    render(<ReaderSpeechPanel {...props} />)
    expect(screen.getByRole('button', { name: 'Read selection' }).hasAttribute('disabled')).toBe(true)
    expect(screen.queryByRole('option', { name: /Cloud voice/ })).toBeNull()
    act(() => { synthesis.voices.push(speechVoice()); synthesis.dispatchEvent(new Event('voiceschanged')) })
    expect(screen.getByRole('button', { name: 'Read selection' }).hasAttribute('disabled')).toBe(false)
    expect(screen.getAllByRole('option').some(option => option.textContent?.includes('Cloud'))).toBe(false)
  })
  it('requires opt-in for browser online voices, labels the provider and previews only after a click', async () => {
    const online = speechVoice('vi-VN', false, 'Microsoft HoaiMy Online (Natural) - Vietnamese (Vietnam)')
    synthesis.voices = [speechVoice('vi-VN', true, 'Microsoft An - Vietnamese (Vietnam)'), online]
    render(<ReaderSpeechPanel {...props} />)
    const permission = screen.getByRole('checkbox', { name: 'Allow Google/Microsoft online voices' })
    expect(permission).toHaveProperty('checked', false)
    expect(screen.queryByRole('option', { name: /HoaiMy/ })).toBeNull()
    fireEvent.click(permission)
    expect(synthesis.spoken).toHaveLength(0)
    expect(source).not.toHaveBeenCalled()
    expect((screen.getByLabelText('Voice') as HTMLSelectElement).selectedOptions[0].textContent).toContain('HoaiMy')
    expect(screen.getByRole('option', { name: /HoaiMy/ }).textContent).toContain('Online Microsoft')
    expect(screen.getByText(/Using an online Microsoft voice/)).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Preview voice' }))
    await waitFor(() => expect(synthesis.spoken).toHaveLength(1))
    expect(synthesis.spoken[0].voice).toBe(online)
    expect(synthesis.spoken[0].text).toContain('Chào bạn')
    expect(source).not.toHaveBeenCalled()
    const cancels = synthesis.cancel.mock.calls.length
    fireEvent.click(permission)
    expect(synthesis.cancel.mock.calls.length).toBeGreaterThan(cancels)
    expect(screen.queryByRole('option', { name: /HoaiMy/ })).toBeNull()
    expect(screen.getByText(/Using a local voice/)).toBeTruthy()
    act(() => synthesis.spoken[0].end())
    expect(synthesis.spoken).toHaveLength(1)
    expect(screen.queryByRole('button', { name: 'Pause' })).toBeNull()
  })
  it('cancels pending chapter text when online permission changes and never reads a late response', async () => {
    const pending = deferred<ReaderSpeechText>(); source.mockReturnValueOnce(pending.promise)
    synthesis.voices.push(speechVoice('vi-VN', false, 'Google tiếng Việt'))
    render(<ReaderSpeechPanel {...props} />)
    const permission = screen.getByRole('checkbox', { name: 'Allow Google/Microsoft online voices' })
    fireEvent.click(permission)
    fireEvent.click(screen.getByRole('button', { name: 'Read current section' }))
    const signal = source.mock.calls[0][0]
    fireEvent.click(permission)
    expect(signal.aborted).toBe(true)
    await act(async () => { pending.resolve({ text: 'Private chapter.', label: '', truncated: false }); await pending.promise })
    expect(synthesis.spoken).toHaveLength(0)
  })
  it('shows unavailable online voices honestly and keeps the local fallback', async () => {
    render(<ReaderSpeechPanel {...props} />)
    fireEvent.click(screen.getByRole('checkbox', { name: 'Allow Google/Microsoft online voices' }))
    expect(screen.getByText(/not offering a supported online voice/)).toBeTruthy()
    expect(screen.getByText(/Using a local voice/)).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Preview voice' }))
    await waitFor(() => expect(synthesis.spoken).toHaveLength(1))
    expect(synthesis.spoken[0].voice?.localService).toBe(true)
    act(() => { synthesis.voices.push(speechVoice('vi-VN', false, 'Microsoft HoaiMy Online (Natural) - Vietnamese (Vietnam)')); synthesis.dispatchEvent(new Event('voiceschanged')) })
    expect(screen.queryByText(/not offering a supported online voice/)).toBeNull()
    // Discovery updates choices, without speaking the document automatically.
    expect(synthesis.spoken).toHaveLength(1)
  })
  it('ignores an async old chapter, resets loading on a new scope and allows a fresh read', async () => {
    const pending = deferred<ReaderSpeechText>(); source.mockReturnValueOnce(pending.promise)
    const { rerender } = render(<ReaderSpeechPanel {...props} />)
    fireEvent.click(screen.getByRole('button', { name: 'Read current section' }))
    const signal = source.mock.calls[0][0]
    rerender(<ReaderSpeechPanel {...props} scopeKey="section:two" />)
    expect(signal.aborted).toBe(true)
    expect(screen.getByRole('button', { name: 'Read current section' }).hasAttribute('disabled')).toBe(false)
    await act(async () => { pending.resolve({ text: 'Stale text', label: 'Old', truncated: false }); await pending.promise })
    expect(synthesis.spoken).toHaveLength(0)
    fireEvent.click(screen.getByRole('button', { name: 'Read current section' }))
    await waitFor(() => expect(synthesis.spoken).toHaveLength(1))
    expect(synthesis.spoken[0].text).toBe('Current chapter text.')
  })
  it('cancels speech and late callbacks when the source changes or the panel unmounts', async () => {
    const { rerender, unmount } = render(<ReaderSpeechPanel {...props} />)
    fireEvent.click(screen.getByRole('button', { name: 'Read selection' }))
    await waitFor(() => expect(synthesis.spoken).toHaveLength(1))
    const old = synthesis.spoken[0], cancels = synthesis.cancel.mock.calls.length
    rerender(<ReaderSpeechPanel {...props} source={null} />)
    expect(synthesis.cancel.mock.calls.length).toBeGreaterThan(cancels)
    act(() => old.end())
    expect(screen.queryByRole('button', { name: 'Pause' })).toBeNull()
    unmount(); old.end(); expect(synthesis.spoken).toHaveLength(1)
  })
  it('reports loading, missing text and synthesis errors with a retry', async () => {
    source.mockRejectedValueOnce(new Error('preparing')).mockRejectedValueOnce(new Error('image-only'))
    render(<ReaderSpeechPanel {...props} />)
    fireEvent.click(screen.getByRole('button', { name: 'Read current section' }))
    expect((await screen.findByRole('alert')).textContent).toContain('still loading')
    fireEvent.click(screen.getByRole('button', { name: 'Read current section' }))
    await waitFor(() => expect(screen.getByRole('alert').textContent).toContain('OCR'))
    fireEvent.click(screen.getByRole('button', { name: 'Read selection' }))
    await waitFor(() => expect(synthesis.spoken).toHaveLength(1))
    act(() => synthesis.spoken[0].fail())
    expect(screen.getByRole('alert').textContent).toContain('could not start')
  })
  it('reports unsupported browsers and unavailable document-language voices honestly', () => {
    synthesis.voices = [speechVoice('en-US')]
    const { unmount } = render(<ReaderSpeechPanel {...props} />)
    expect(screen.getByText(/No local voice matches/)).toBeTruthy()
    unmount(); vi.stubGlobal('SpeechSynthesisUtterance', undefined)
    render(<ReaderSpeechPanel {...props} />)
    expect(screen.getByRole('status').textContent).toContain('does not support')
    expect(screen.queryByRole('button', { name: 'Read selection' })).toBeNull()
  })
  it('keeps voice and speed choices while changing PDF pages, and delegates close', () => {
    const { rerender } = render(<ReaderSpeechPanel {...props} scopeKey="pdf:1" />)
    fireEvent.change(screen.getByLabelText('Speed'), { target: { value: '1.5' } })
    rerender(<ReaderSpeechPanel {...props} scopeKey="pdf:2" />)
    expect((screen.getByLabelText('Speed') as HTMLSelectElement).value).toBe('1.5')
    fireEvent.click(screen.getByRole('button', { name: 'Close read aloud' }))
    expect(props.onClose).toHaveBeenCalledOnce()
  })
  it('keeps browser speech and chosen settings when another sidebar temporarily hides its controls', async () => {
    const male = speechVoice('vi-VN', true, 'Microsoft An - Vietnamese (Vietnam)')
    const female = speechVoice('vi-VN', true, 'Linh')
    synthesis.voices = [male, female]
    const { container, rerender } = render(<ReaderSpeechPanel {...props} bookTitle="Research notes" />)
    const maleOption = screen.getByRole('option', { name: /Microsoft An/ }) as HTMLOptionElement
    fireEvent.change(screen.getByLabelText('Voice'), { target: { value: maleOption.value } })
    fireEvent.change(screen.getByLabelText('Speed'), { target: { value: '1.5' } })
    fireEvent.click(screen.getByRole('button', { name: 'Read current section' }))
    await waitFor(() => expect(synthesis.spoken).toHaveLength(1))
    const utterance = synthesis.spoken[0], cancels = synthesis.cancel.mock.calls.length
    expect(utterance.voice).toBe(male)
    expect(utterance.rate).toBe(1.5)

    rerender(<ReaderSpeechPanel {...props} bookTitle="Research notes" hidden />)
    expect(container.querySelector('#reader-speech-panel')).toHaveProperty('hidden', true)
    expect(screen.queryByRole('button', { name: 'Read current section' })).toBeNull()
    expect(synthesis.cancel).toHaveBeenCalledTimes(cancels)
    expect(synthesis.spoken).toEqual([utterance])

    rerender(<ReaderSpeechPanel {...props} bookTitle="Research notes" />)
    expect((screen.getByLabelText('Voice') as HTMLSelectElement).value).toBe(maleOption.value)
    expect((screen.getByLabelText('Speed') as HTMLSelectElement).value).toBe('1.5')
    expect(screen.getByRole('button', { name: 'Pause' })).toBeTruthy()
    expect(synthesis.cancel).toHaveBeenCalledTimes(cancels)
    expect(synthesis.speak).toHaveBeenCalledOnce()
    expect(source).toHaveBeenCalledOnce()
  })
})

describe('Achernar sample in the read aloud panel', () => {
  beforeEach(() => {
    vi.spyOn(HTMLMediaElement.prototype, 'play').mockImplementation(function (this: HTMLMediaElement) {
      this.dispatchEvent(new Event('play'))
      this.dispatchEvent(new Event('playing'))
      return Promise.resolve()
    })
    vi.spyOn(HTMLMediaElement.prototype, 'pause').mockImplementation(function (this: HTMLMediaElement) {
      this.dispatchEvent(new Event('pause'))
    })
    vi.spyOn(HTMLMediaElement.prototype, 'load').mockImplementation(() => {})
  })
  afterEach(() => { cleanup(); vi.restoreAllMocks() })

  it('offers one fixed sample only after an explicit click, without reading the book', () => {
    const { container } = render(<ReaderSpeechPanel {...props} />)
    expect(container.querySelector('audio')).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: 'Try Achernar' }))
    expect(container.querySelector('audio')).toBeNull()
    expect(screen.queryByRole('button', { name: 'Read current section' })).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: 'Play Achernar sample' }))
    expect(container.querySelector('audio')?.getAttribute('src')).toBe('https://docs.cloud.google.com/static/text-to-speech/docs/audio/vi-VN-Chirp3-HD-Achernar.wav')
    expect(container.querySelectorAll('audio')).toHaveLength(1)
    expect(screen.queryByText(/Vindemiatrix|Leda/)).toBeNull()
    expect(source).not.toHaveBeenCalled()
    expect(synthesis.spoken).toHaveLength(0)
  })

  it('cancels pending book speech when switching to the sample and ignores its late result', async () => {
    const pending = deferred<ReaderSpeechText>(); source.mockReturnValueOnce(pending.promise)
    render(<ReaderSpeechPanel {...props} />)
    fireEvent.click(screen.getByRole('button', { name: 'Read current section' }))
    const signal = source.mock.calls[0][0]
    fireEvent.click(screen.getByRole('button', { name: 'Try Achernar' }))
    expect(signal.aborted).toBe(true)
    await act(async () => { pending.resolve({ text: 'Private book text.', label: '', truncated: false }); await pending.promise })
    fireEvent.click(screen.getByRole('button', { name: 'Play Achernar sample' }))
    expect(synthesis.spoken).toHaveLength(0)
    expect(screen.getByRole('status').textContent).toContain('Playing sample')
  })

  it('stops current browser speech before auditioning the sample', async () => {
    render(<ReaderSpeechPanel {...props} />)
    fireEvent.click(screen.getByRole('button', { name: 'Read selection' }))
    await waitFor(() => expect(synthesis.spoken).toHaveLength(1))
    const cancels = synthesis.cancel.mock.calls.length
    fireEvent.click(screen.getByRole('button', { name: 'Try Achernar' }))
    expect(synthesis.cancel.mock.calls.length).toBeGreaterThan(cancels)
    fireEvent.click(screen.getByRole('button', { name: 'Play Achernar sample' }))
    act(() => synthesis.spoken[0].end())
    expect(synthesis.spoken).toHaveLength(1)
    expect(screen.getByRole('status').textContent).toContain('Playing sample')
  })

  it('keeps sample playback available without Web Speech support', () => {
    vi.stubGlobal('SpeechSynthesisUtterance', undefined)
    render(<ReaderSpeechPanel {...props} />)
    fireEvent.click(screen.getByRole('button', { name: 'Try Achernar' }))
    fireEvent.click(screen.getByRole('button', { name: 'Play Achernar sample' }))
    expect(screen.getByRole('status').textContent).toContain('Playing sample')
    expect(source).not.toHaveBeenCalled()
  })

  it('disposes a playing sample when hidden and never restarts it just by reopening the sidebar', () => {
    const { container, rerender } = render(<ReaderSpeechPanel {...props} />)
    fireEvent.click(screen.getByRole('button', { name: 'Try Achernar' }))
    fireEvent.click(screen.getByRole('button', { name: 'Play Achernar sample' }))
    const first = container.querySelector('audio')!
    expect(screen.getByRole('status').textContent).toContain('Playing sample')
    expect(HTMLMediaElement.prototype.play).toHaveBeenCalledOnce()

    rerender(<ReaderSpeechPanel {...props} hidden />)
    expect(first.getAttribute('src')).toBeNull()
    expect(first.isConnected).toBe(false)
    expect(HTMLMediaElement.prototype.pause).toHaveBeenLastCalledWith()
    expect(vi.mocked(HTMLMediaElement.prototype.pause).mock.contexts.at(-1)).toBe(first)
    expect(container.querySelector('audio')).toBeNull()
    expect(screen.queryByRole('button', { name: 'Play Achernar sample' })).toBeNull()

    rerender(<ReaderSpeechPanel {...props} />)
    expect(screen.getByRole('button', { name: 'Try Achernar' }).getAttribute('aria-pressed')).toBe('true')
    expect(screen.getByRole('button', { name: 'Play Achernar sample' })).toBeTruthy()
    expect(container.querySelector('audio')).toBeNull()
    expect(screen.queryByRole('status')).toBeNull()
    expect(HTMLMediaElement.prototype.play).toHaveBeenCalledOnce()
    fireEvent.click(screen.getByRole('button', { name: 'Play Achernar sample' }))
    expect(container.querySelector('audio')).not.toBe(first)
    expect(HTMLMediaElement.prototype.play).toHaveBeenCalledTimes(2)
    expect(source).not.toHaveBeenCalled()
    expect(synthesis.spoken).toHaveLength(0)
  })

  it('disposes the sample on a page change, mode change, panel close and unmount', () => {
    const { container, rerender, unmount } = render(<ReaderSpeechPanel {...props} />)
    fireEvent.click(screen.getByRole('button', { name: 'Try Achernar' }))
    const play = () => {
      fireEvent.click(screen.getByRole('button', { name: 'Play Achernar sample' }))
      return container.querySelector('audio')!
    }
    const first = play()
    rerender(<ReaderSpeechPanel {...props} scopeKey="section:two" />)
    expect(first.getAttribute('src')).toBeNull()
    expect(first.isConnected).toBe(false)
    expect(container.querySelector('audio')).toBeNull()
    const second = play()
    fireEvent.click(screen.getByRole('button', { name: 'Browser voices' }))
    expect(second.getAttribute('src')).toBeNull()
    expect(screen.getByRole('button', { name: 'Read current section' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Try Achernar' }))
    const third = play()
    fireEvent.click(screen.getByRole('button', { name: 'Close read aloud' }))
    expect(third.getAttribute('src')).toBeNull()
    expect(props.onClose).toHaveBeenCalledOnce()
    fireEvent.click(screen.getByRole('button', { name: 'Try Achernar' }))
    const fourth = play()
    unmount()
    expect(fourth.getAttribute('src')).toBeNull()
    expect(fourth.isConnected).toBe(false)
  })
})
